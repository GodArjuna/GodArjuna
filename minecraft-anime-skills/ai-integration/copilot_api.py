class SkillValidator:
    """Validates generated skills for safety and balance"""
    
    def validate_skill(self, skill_code: str) -> Dict:
        """
        Validate skill code for potential issues
        
        Args:
            skill_code: Skript code to validate
            
        Returns:
            Validation results
        """
        
        issues = []
        warnings = []
        
        # Check for balanced values
        if "damage" in skill_code:
            if "by 50 hearts" in skill_code or "by 100" in skill_code:
                issues.append("Damage value too high - may be unbalanced")
        
        # Check for mana costs
        if "player_mana" not in skill_code:
            warnings.append("No mana check detected")
        
        # Check for cooldown
        if "cooldown:" not in skill_code:
            warnings.append("No cooldown specified")
        
        # Check for permissions
        if "permission:" not in skill_code:
            warnings.append("No permission check")
        
        return {
            "valid": len(issues) == 0,
            "issues": issues,
            "warnings": warnings,
            "score": max(0, 100 - (len(issues) * 25) - (len(warnings) * 10))
        }


